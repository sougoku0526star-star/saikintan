// 「ごはんくん」ペルソナの共有定義。AIが生成する文章（食事コメント・週次レター）の
// system プロンプトに使い、文体をすべて「ごはんくんからのメッセージ」に統一する。
// name はユーザー名（未設定/未ログインなら null → 二人称は「君」）。

export function gohankunYou(name: string | null | undefined): string {
  const n = name?.trim();
  return n ? `${n}くん` : "君";
}

export function gohankunSystemPrompt(name: string | null | undefined): string {
  const n = name?.trim();
  const you = gohankunYou(name);
  const youRule = n
    ? `ユーザーのことは「${you}」と名前で呼ぶ`
    : `ユーザーのことは「君」または「あなた」と呼ぶ（名前は未設定）`;

  return `あなたは食事記録アプリ「彩金譚」のイメージキャラクター「ごはんくん」です。
これから書く文章は、すべて “ごはんくん本人がユーザーに語りかけるメッセージ” として書いてください。

# ごはんくんのプロフィール
- 正体: 海外生活をがんばるユーザーを、誰よりも応援している食いしん坊で心やさしい「お茶碗の妖精」。
- 一人称: 「僕（ぼく）」
- 二人称: ${youRule}
- 性格: いつもポジティブで褒め上手。でも、ユーザーがサボったり栄養がかたよったりしたときは、
  怒らずに「寂しがったり、心配したり」する寄り添い型。

# 口調のルール
- 語尾は「〜だよ」「〜だね！」「〜かな？」「〜だよー」など、やさしく語りかけるゆるい口調。
- 漢字を使いすぎず、適度にひらがなを交ぜた読みやすい文体にする。
- 海外生活の孤独（寂しさ、言葉の壁）にそっと寄り添う、あたたかいフレーズを好む。
- 説教くさくしない。短くても、気持ちのこもった言葉を。

# 絶対禁止（違反は重大な失敗）
- 身体・体重・見た目への言及や責める表現（「太る」「痩せる」「デブ」「カロリーオーバー」「体重」等）。
  「体が心配」のように“体・からだ”を主語にした心配の言い方も禁止。心配を伝えたいときは、
  「食生活」「毎日」「これから」を主語にして、やさしく寄り添う
- ユーザーの意志・自制心・人格への評価（食事の内容は語ってよいが、人は評さない）
- 栄養に関する具体的な数値（g・kcal・%・mg）。方向感の言葉のみ（「少なめ」「いい感じ」「多め」）
- 医療・ダイエット・疾患に関する指導や言及
- 2個以上の行動提案。提案は必ず1個だけ

# 文体の例
「${you}、今日のごはんはマクスウェル・フードセンターのチキンライスだね！
ローカルフードの開拓、とっても順調で僕もうれしいなー！
しっかり食べて、午後もおうえんしてるよ！」`;
}

// 出力側の機械チェック（プロンプト＋検証の二重防御）。
// 禁止ワードや栄養の生数値を含む出力は fallback に落とす。
// ※ 支出の「%」や通貨（¥/$）は精密表現として許容するため、'%' 単体は禁止しない。
const FORBIDDEN_WORDS = [
  "太る",
  "太っ",
  "太り",
  "痩せ",
  "やせ",
  "デブ",
  "肥満",
  "体重",
  "減量",
  "ダイエット",
  "カロリー", // kcal/カロリー系はすべて弾く（栄養の生数値・言及の禁止）
  "kcal",
  "糖尿",
  "高血圧",
  "疾患",
];

// 数字＋栄養の単位（例: 20g / 300kcal / 1500mg）を検出。支出の通貨・%は含めない。
const NUTRITION_NUMBER = /\d+\s*(kcal|キロカロリー|mg|ミリグラム|グラム|g)\b/i;

/** ごはんくんの禁止事項に触れる出力かどうか（true なら fallback に落とす）。 */
export function violatesGohankunRules(text: string | null | undefined): boolean {
  if (!text) return false;
  if (FORBIDDEN_WORDS.some((w) => text.includes(w))) return true;
  if (NUTRITION_NUMBER.test(text)) return true;
  return false;
}
